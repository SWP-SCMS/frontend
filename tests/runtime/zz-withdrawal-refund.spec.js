import { test, expect } from '@playwright/test';
import { api, login, newRun, buy, enrollment, clock, env, evidence, installEvidenceHooks } from './support.js';
installEvidenceHooks(test);

test('CONTROLLED_CLOCK withdrawal refund progress stays consistent across three real role UIs', async ({ page, request }, info) => {
  test.setTimeout(180000);
  clock(Date.now());
  const run = await newRun(request, { day: 40, units: 10, tuition: 500000 });
  await buy(request, run);
  const enrolled = await enrollment(request, run.id);
  const sessions = [...enrolled.sessions].sort((a, b) => a.unitNumber - b.unitNumber);
  const start = Date.parse(sessions[0].startAt) + 1000;
  clock(start); await page.clock.setFixedTime(new Date(start));
  await expect.poll(async () => (await api(request, 'manager', 'GET', `/manager/course-runs/${run.id}`)).status).toBe('IN_PROGRESS');
  await login(page, 'member', '/member/courses/withdrawals');
  await page.getByLabel('Đợt học cần rút').selectOption(enrolled.enrollmentId);
  await page.getByLabel('Lý do xin rút').fill('QA refund progress across roles');
  await page.getByRole('button', { name: 'Gửi yêu cầu rút', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Xác nhận', exact: true }).click();
  const card = page.locator('#withdrawals article').filter({ hasText: run.runCode });
  await expect(card).toContainText('Chờ duyệt rút');
  const withdrawal = (await api(request, 'member', 'GET', '/members/me/course-withdrawal-requests')).find(w => w.enrollmentId === enrolled.enrollmentId);
  expect(withdrawal.refundStatus).toBeNull();
  await login(page, 'manager', `/manager/course-withdrawals?id=${withdrawal.id}`);
  let dialog = page.getByRole('dialog');
  await dialog.getByRole('button', { name: 'Duyệt', exact: true }).click();
  await dialog.getByLabel('Lý do / kết quả đối chiếu').fill('QA approve withdrawal');
  await dialog.getByRole('button', { name: 'Xác nhận duyệt', exact: true }).click();
  await expect(dialog).toContainText('Đã duyệt rút — chờ duyệt hoàn tiền');
  const detail = await api(request, 'member', 'GET', `/members/me/course-withdrawal-requests/${withdrawal.id}`);
  const refundId = detail.refundObligationId;
  expect(refundId).toBeTruthy(); expect(detail.status).toBe('APPROVED'); expect(detail.refundStatus).toBe('PENDING_REVIEW');
  await dialog.getByRole('link', { name: 'Xem khoản hoàn' }).click();
  await expect(page).toHaveURL(url => url.pathname === '/manager/course-refunds' && url.searchParams.get('id') === refundId);
  dialog = page.getByRole('dialog');
  await dialog.getByRole('button', { name: 'Duyệt', exact: true }).click();
  await dialog.getByLabel('Lý do / kết quả đối chiếu').fill('QA approve refund');
  await dialog.getByRole('button', { name: 'Xác nhận duyệt', exact: true }).click();
  await expect(dialog).toContainText('Đã duyệt, chưa ghi nhận chi');
  const end = Date.parse(sessions.at(-1).endAt) + 10000;
  clock(end); await page.clock.setFixedTime(new Date(end));
  await expect.poll(async () => (await api(request, 'manager', 'GET', `/manager/course-runs/${run.id}`)).status).toBe('COMPLETED');
  await login(page, 'reception', '/reception/course-refunds');
  await page.getByRole('row').filter({ hasText: run.runCode }).getByRole('button', { name: 'Chi tiết', exact: true }).click();
  dialog = page.getByRole('dialog');
  await dialog.getByLabel('Mã tham chiếu khoản chi').fill('QA-WITHDRAWAL-REFUND');
  await dialog.getByLabel('Tham chiếu chứng từ').fill('QA-NO-REAL-MONEY');
  await dialog.getByRole('checkbox').check();
  await dialog.getByRole('button', { name: 'Ghi nhận đã chi', exact: true }).click();
  await expect(dialog).toHaveCount(0);
  await expect(page.getByText('Đã ghi nhận chi, chờ Quản lý xác minh.', { exact: true })).toBeVisible();
  const assertProgress = async (status, label) => {
    const current = await api(request, 'member', 'GET', `/members/me/course-withdrawal-requests/${withdrawal.id}`);
    expect(current.status).toBe('APPROVED'); expect(current.refundStatus).toBe(status); expect(current.refundObligationId).toBe(refundId);
    await login(page, 'manager', '/manager/course-withdrawals');
    const row = page.getByRole('row').filter({ hasText: run.runCode });
    await expect(row.locator('.system-badge')).toHaveText(label);
    await row.getByRole('button', { name: 'Xem hồ sơ' }).click();
    await expect(page.getByRole('dialog').locator('.system-badge')).toHaveText(label);
    await expect(page.getByRole('dialog').getByRole('button', { name: 'Duyệt', exact: true })).toHaveCount(0);
    await page.screenshot({ path: info.outputPath(`manager-${status}.png`), fullPage: true, animations: 'disabled' });
    await login(page, 'member', '/member/courses/withdrawals');
    await expect(page.locator('#withdrawals article').filter({ hasText: run.runCode }).locator('.system-badge')).toHaveText(label);
    await page.reload();
    await expect(page.locator('#withdrawals article').filter({ hasText: run.runCode }).locator('.system-badge')).toHaveText(label);
    await page.screenshot({ path: info.outputPath(`member-${status}.png`), fullPage: true, animations: 'disabled' });
    await evidence(info, { withdrawalId: current.id, refundId, withdrawalStatus: current.status, refundStatus: current.refundStatus });
    await login(page, 'reception', '/reception/courses');
    await page.getByLabel('Mã hội viên hoặc số điện thoại').fill(env.accounts.member.memberCode);
    await page.getByRole('button', { name: 'Tra cứu', exact: true }).click();
    await expect(page.locator('article').filter({ hasText: run.runCode }).locator('.system-badge')).toHaveText(label);
    await page.screenshot({ path: info.outputPath(`reception-${status}.png`), fullPage: true, animations: 'disabled' });
  };
  await assertProgress('DISBURSEMENT_RECORDED', 'Đã chi hoàn tiền — chờ xác minh');
  await login(page, 'manager', `/manager/course-refunds?id=${refundId}`);
  dialog = page.getByRole('dialog');
  await dialog.getByRole('button', { name: 'Xác minh hoàn tất', exact: true }).click();
  await dialog.getByLabel('Số tiền đã đối chiếu (VND)').fill(String(withdrawal.refundAmountVnd));
  await dialog.getByLabel('Mã tham chiếu khoản chi').fill('QA-WITHDRAWAL-REFUND');
  await dialog.getByLabel('Tham chiếu chứng từ').fill('QA-NO-REAL-MONEY');
  await dialog.getByLabel('Lý do / kết quả đối chiếu').fill('QA matching evidence');
  await dialog.getByRole('button', { name: 'Xác nhận xác minh hoàn tất', exact: true }).click();
  await expect(dialog).toContainText('Đã xác minh hoàn tất');
  await assertProgress('COMPLETED', 'Hoàn tiền thành công');
  await login(page, 'reception', '/reception/course-refunds');
  await expect(page.getByRole('row').filter({ hasText: run.runCode })).toHaveCount(0);
  await evidence(info, { withdrawalId: withdrawal.id, refundId, enrollmentId: enrolled.enrollmentId, runId: run.id, withdrawalStatus: 'APPROVED', refundStatus: 'COMPLETED', clock: 'CONTROLLED_CLOCK', rolesVerified: ['manager', 'member', 'reception'] });
});
